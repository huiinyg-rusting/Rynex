/// Map a Unicode code point to a glyph index in FONT_8X16.
fn glyph_for(c: char) -> u8 {
    let cp = c as u32;
    match cp {
        0x00..=0x1F | 0x7F => 0,
        0x00A0 => 0x20, // NBSP
        0x20..=0x7E => (cp - 0x20 + 0x20) as u8,
        0x2423 => 0xA0, // OPEN BOX
        0xA1..=0xBF => (cp - 0xA1 + 0xA1) as u8,
        0xC0..=0xDF => (cp - 0xC0 + 0x80) as u8,
        0xE0..=0xFF => (cp - 0xE0 + 0xE0) as u8,
        0x2500 => 0xCA, 0x2501 => 0xDA,
        0x2502 => 0xC5, 0x2503 => 0xD5,
        0x250C => 0xC6, 0x250F => 0xD6,
        0x2510 => 0xCC, 0x2513 => 0xDC,
        0x2514 => 0xC3, 0x2517 => 0xD3,
        0x2518 => 0xC9, 0x251B => 0xD9,
        0x251C => 0xC7, 0x2523 => 0xD7,
        0x2524 => 0xCD, 0x252B => 0xDD,
        0x252C => 0xCE, 0x2533 => 0xDE,
        0x2534 => 0xCB, 0x253B => 0xDB,
        0x253C => 0xCF, 0x254B => 0xDF,
        0x2550 => 0xDA, 0x2551 => 0xD5, 0x2554 => 0xD6, 0x2557 => 0xDC,
        0x255A => 0xD3, 0x255D => 0xD9, 0x2560 => 0xD7, 0x2563 => 0xDD,
        0x2566 => 0xDE, 0x2569 => 0xDB, 0x256C => 0xDF,
        0x2574 => 0xC8, 0x2575 => 0xC1, 0x2576 => 0xC2, 0x2577 => 0xC4,
        0x2578 => 0xD8, 0x2579 => 0xD1, 0x257A => 0xD2, 0x257B => 0xD4,
        // Soft hyphen falls inside 0xA1..=0xBF above and maps to glyph 0xAD.
        _ => 0x3F, // '?'
    }
}

