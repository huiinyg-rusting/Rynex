//! Framebuffer console (fbcon).
//!
//! Renders a built-in 8x16 bitmap font into the linear framebuffer that GRUB
//! provides via the Multiboot2 framebuffer tag (type 8). Supports direct-RGB
//! modes: 32bpp (XRGB8888), 24bpp and 15/16bpp (mask/position driven, so
//! both 555 and 565 work). This is the display path on UEFI handoffs and on
//! BIOS boots that requested a gfxpayload; legacy text-only boots keep the
//! 0xB8000 VGA text path (see crate::vga).
//!
//! The font covers ASCII, Latin-1 and the common box-drawing block. Any
//! UTF-8 code point that has no glyph is rendered as '?'.

use core::sync::atomic::{AtomicBool, Ordering};

use crate::spinlock::RawSpin;

pub const FONT_W: u32 = 8;
pub const FONT_H: u32 = 16;

#[derive(Clone, Copy)]
pub struct FbInfo {
    pub addr: u64,
    pub pitch: u32,
    pub width: u32,
    pub height: u32,
    pub bpp: u8,
    pub fb_type: u8,
    pub red_pos: u8,
    pub red_mask: u8,
    pub green_pos: u8,
    pub green_mask: u8,
    pub blue_pos: u8,
    pub blue_mask: u8,
}

// The boot identity map (boot.asm) covers the first 1 GiB with 2 MiB huge
// pages. GRUB/QEMU place the LFB at ~0xFD000000 on BIOS VBE, which is well
// BEYOND that limit, so init() only validates and stores the tag; the actual
// mapping happens in enable_console() once paging is up. An fb that sits
// outside (or straddles) the identity map is remapped page by page into the
// kernel direct map at KERNEL_BASE+phys (same pattern as the LAPIC), and the
// console is pointed at that high address.
const IDENTITY_LIMIT: u64 = 1 << 30;

static ENABLED: AtomicBool = AtomicBool::new(false);

static mut PENDING: Option<FbInfo> = None;

static mut FB: FbInfo = FbInfo {
    addr: 0,
    pitch: 0,
    width: 0,
    height: 0,
    bpp: 0,
    fb_type: 1,
    red_pos: 16,
    red_mask: 8,
    green_pos: 8,
    green_mask: 8,
    blue_pos: 0,
    blue_mask: 8,
};

static mut COL: u32 = 0;
static mut ROW: u32 = 0;
static mut FG: u32 = 0xFF_FF_FF;
static mut BG: u32 = 0x00_00_00;

static FB_LOCK: RawSpin = RawSpin::new();

fn fb_bytes_per_pixel(bpp: u8) -> usize {
    match bpp {
        32 => 4,
        24 => 3,
        15 | 16 => 2,
        _ => 0,
    }
}

/// Validate a Multiboot2 framebuffer tag and register it as pending. Early,
/// single threaded, runs before paging exists, so NO writes happen here. The
/// console is only switched on by enable_console() once the page tables are
/// up (see bootmode::install_framebuffer / main).
pub fn init(info: &FbInfo) {
    if info.width < FONT_W || info.height < FONT_H {
        crate::serial::write_str("FB: refused (mode too small)\n");
        unsafe { PENDING = None; }
        return;
    }
    if info.fb_type != crate::multiboot2::FB_TYPE_RGB {
        crate::serial::write_str("FB: refused (non-RGB framebuffer type)\n");
        unsafe { PENDING = None; }
        return;
    }
    if fb_bytes_per_pixel(info.bpp) == 0 {
        crate::serial::write_str("FB: refused (unsupported bpp ");
        crate::serial::write_dec(info.bpp as u64);
        crate::serial::write_str(")\n");
        unsafe { PENDING = None; }
        return;
    }
    let end = info
        .addr
        .checked_add(info.pitch as u64 * info.height as u64);
    if end.is_none() {
        crate::serial::write_str("FB: refused (framebuffer range overflow)\n");
        unsafe { PENDING = None; }
        return;
    }
    unsafe { PENDING = Some(*info); }
}

/// Turn the pending, validated framebuffer into an active console. Must be
/// called after paging::init(): an fb outside (or straddling) the 1 GiB boot
/// identity map is mapped into the kernel direct map (KERNEL_BASE+phys) and
/// the console is pointed at that address. Returns true when enabled.
pub fn enable_console() -> bool {
    let info = match unsafe { PENDING } {
        Some(i) => i,
        None => return false,
    };
    unsafe { PENDING = None; }

    let mut info = info;
    let size = info.pitch as u64 * info.height as u64;
    let in_identity = info.addr < IDENTITY_LIMIT
        && info.addr.checked_add(size).map_or(false, |e| e <= IDENTITY_LIMIT);
    if !in_identity {
        if !map_fb_range(info.addr, size) {
            crate::serial::write_str("FB: enable failed (mapping beyond identity map)\n");
            return false;
        }
        let virt = crate::paging::KERNEL_BASE + info.addr;
        crate::serial::write_str("FB: mapped phys=0x");
        crate::serial::write_hex(info.addr);
        crate::serial::write_str(" -> virt=0x");
        crate::serial::write_hex(virt);
        crate::serial::write_str("\n");
        info.addr = virt;
    }
    unsafe {
        FB = info;
        COL = 0;
        ROW = 0;
    }
    ENABLED.store(true, Ordering::SeqCst);
    clear();
    crate::serial::write_str("FB: console enabled (");
    crate::serial::write_dec(info.width as u64);
    crate::serial::write_char('x');
    crate::serial::write_dec(info.height as u64);
    crate::serial::write_char('x');
    crate::serial::write_dec(info.bpp as u64);
    crate::serial::write_str(" @0x");
    crate::serial::write_hex(info.addr);
    crate::serial::write_str(")\n");
    true
}

/// Map a physical framebuffer range into the kernel direct map one 4 KiB page
/// at a time, so the fb is writable even though it lies beyond the 1 GiB boot
/// identity map. Uses the same PAGING_LOCK-disciplined map_kernel_page() the
/// kernel uses for every other high-half mapping.
fn map_fb_range(phys: u64, size: u64) -> bool {
    let start = phys & !0xFFFu64;
    let end = phys.saturating_add(size).saturating_add(0xFFF) & !0xFFFu64;
    let mut p = start;
    while p < end {
        let virt = crate::paging::KERNEL_BASE + p;
        match crate::paging::PageTableManager::map_kernel_page(
            virt,
            p,
            crate::paging::PTE_WRITABLE | crate::paging::PTE_NO_EXECUTE,
        ) {
            Ok(()) => {}
            Err(_) => return false,
        }
        unsafe {
            core::arch::asm!("invlpg [{}]", in(reg) virt, options(nostack, preserves_flags));
        }
        p += 0x1000;
    }
    true
}

/// Read one raw pixel value back from the framebuffer, as serial evidence the
/// display path really writes the linear framebuffer. Returns 0xFF_FF_FF_FF
/// when the console is disabled and 0xFF_FF_FF_FE for out-of-bounds reads.
pub fn probe_pixel(x: u32, y: u32) -> u32 {
    let _g = FB_LOCK.lock();
    if !ENABLED.load(Ordering::Relaxed) {
        return 0xFF_FF_FF_FF;
    }
    let fb = unsafe { &FB };
    if x >= fb.width || y >= fb.height {
        return 0xFF_FF_FF_FE;
    }
    let bytes = fb_bytes_per_pixel(fb.bpp);
    let off = y as u64 * fb.pitch as u64 + x as u64 * bytes as u64;
    let base = fb.addr.wrapping_add(off) as *const u8;
    let mut v: u32 = 0;
    for i in 0..bytes {
        v |= (unsafe { base.add(i).read_volatile() } as u32) << (8 * i);
    }
    v
}

pub fn active() -> bool {
    ENABLED.load(Ordering::Relaxed)
}

/// Diagnostic: (FG, BG, fb addr) for verifying the draw state.
pub fn debug_fb() -> (u32, u32, u64) {
    (unsafe { FG }, unsafe { BG }, unsafe { FB.addr })
}

/// Set the text colour from packed 0xRRGGBB values.
pub fn set_color(fg: u32, bg: u32) {
    let _g = FB_LOCK.lock();
    unsafe {
        FG = fg;
        BG = bg;
    }
}

fn cols() -> u32 {
    unsafe { FB.width / FONT_W }
}

fn rows() -> u32 {
    unsafe { FB.height / FONT_H }
}

/// Fill the whole framebuffer with the background colour and reset the cursor.
pub fn clear() {
    let _g = FB_LOCK.lock();
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    let fb = unsafe { &FB };
    let bg = unsafe { BG };
    for x in 0..fb.width {
        put_pixel_locked(fb, x, 0, (bg >> 16) as u8, (bg >> 8) as u8, bg as u8);
    }
    let src = fb.addr as *const u8;
    for y in 1..fb.height {
        let dst = fb.addr.wrapping_add(y as u64 * fb.pitch as u64) as *mut u8;
        copy_scanline(src, dst, fb.pitch as usize);
    }
    unsafe {
        COL = 0;
        ROW = 0;
    }
}

#[inline(always)]
fn copy_scanline(src: *const u8, dst: *mut u8, bytes: usize) {
    let mut i = 0;
    while i + 8 <= bytes {
        unsafe {
            dst.add(i)
                .cast::<u64>()
                .write_volatile(src.add(i).cast::<u64>().read_volatile());
        }
        i += 8;
    }
    while i < bytes {
        unsafe {
            dst.add(i).write_volatile(src.add(i).read_volatile());
        }
        i += 1;
    }
}

pub fn newline() {
    let _g = FB_LOCK.lock();
    newline_locked();
}

fn newline_locked() {
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    let r = rows();
    unsafe {
        COL = 0;
        ROW += 1;
        if ROW >= r {
            scroll_locked();
            ROW = r - 1;
        }
    }
}

pub fn carriage_return() {
    let _g = FB_LOCK.lock();
    if ENABLED.load(Ordering::Relaxed) {
        unsafe { COL = 0; }
    }
}

pub fn home() {
    let _g = FB_LOCK.lock();
    if ENABLED.load(Ordering::Relaxed) {
        unsafe {
            COL = 0;
            ROW = 0;
        }
    }
}

pub fn backspace() {
    let _g = FB_LOCK.lock();
    backspace_locked();
}

fn backspace_locked() {
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    if unsafe { COL } > 0 {
        unsafe { COL -= 1; }
        clear_cell_locked(unsafe { COL }, unsafe { ROW });
    }
}

fn clear_cell_locked(x: u32, y: u32) {
    let fb = unsafe { &FB };
    let bg = unsafe { BG };
    let x0 = x * FONT_W;
    let y0 = y * FONT_H;
    for yy in 0..FONT_H {
        for xx in 0..FONT_W {
            put_pixel_locked(fb, x0 + xx, y0 + yy, (bg >> 16) as u8, (bg >> 8) as u8, bg as u8);
        }
    }
}

fn scroll_locked() {
    let fb = unsafe { &FB };
    let scan_bytes = fb.pitch as usize;
    for y in FONT_H..fb.height {
        let dst = fb.addr.wrapping_add((y - FONT_H) as u64 * fb.pitch as u64) as *mut u8;
        let src = fb.addr.wrapping_add(y as u64 * fb.pitch as u64) as *const u8;
        copy_scanline(src, dst, scan_bytes);
    }
    let bg = unsafe { BG };
    for y in (fb.height - FONT_H)..fb.height {
        for x in 0..fb.width {
            put_pixel_locked(fb, x, y, (bg >> 16) as u8, (bg >> 8) as u8, bg as u8);
        }
    }
}

/// Erase everything below the cursor (ESC[J).
pub fn erase_to_bottom() {
    let _g = FB_LOCK.lock();
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    let (cr, ccol) = (unsafe { ROW }, unsafe { COL });
    for y in cr..rows() {
        let sx = if y == cr { ccol } else { 0 };
        for x in sx..cols() {
            clear_cell_locked(x, y);
        }
    }
}

pub fn write_char(c: char) {
    let _g = FB_LOCK.lock();
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    match c {
        '\n' => newline_locked(),
        '\r' => unsafe { COL = 0; },
        '\t' => {
            let sp = 4 - (unsafe { COL } % 4);
            for _ in 0..sp {
                draw_glyph_locked(' ');
            }
        }
        '\x08' => backspace_locked(),
        _ => draw_glyph_locked(c),
    }
}

fn draw_glyph_locked(c: char) {
    let c = if (c as u32) < 0x20 || (c as u32) == 0x7F { ' ' } else { c };
    let glyph = glyph_for(c);
    let fb = unsafe { &FB };
    if unsafe { COL } >= cols() {
        newline_locked();
    }
    let x0 = unsafe { COL } * FONT_W;
    let y0 = unsafe { ROW } * FONT_H;
    let base = (glyph as usize) * 16;
    let fg = unsafe { FG };
    let bg = unsafe { BG };
    let (fgr, fgg, fgb) = ((fg >> 16) as u8, (fg >> 8) as u8, fg as u8);
    let (bgr, bgg, bgb) = ((bg >> 16) as u8, (bg >> 8) as u8, bg as u8);
    for r in 0..16usize {
        let scan = FONT_8X16[base + r];
        for x in 0..8u32 {
            if (scan >> (7 - x)) & 1 != 0 {
                put_pixel_locked(fb, x0 + x, y0 + r as u32, fgr, fgg, fgb);
            } else {
                put_pixel_locked(fb, x0 + x, y0 + r as u32, bgr, bgg, bgb);
            }
        }
    }
    unsafe { COL += 1; }
}

fn put_pixel_locked(fb: &FbInfo, x: u32, y: u32, r: u8, g: u8, b: u8) {
    let bytes = fb_bytes_per_pixel(fb.bpp);
    let off = y as u64 * fb.pitch as u64 + x as u64 * bytes as u64;
    let base = fb.addr.wrapping_add(off) as *mut u8;
    let enc = encode_pixel(fb, r, g, b);
    for i in 0..bytes {
        unsafe {
            base.add(i).write_volatile(((enc >> (8 * i)) & 0xFF) as u8);
        }
    }
}

#[inline(always)]
fn encode_pixel(fb: &FbInfo, r: u8, g: u8, b: u8) -> u32 {
    let red = scale(r, fb.red_mask) << fb.red_pos;
    let green = scale(g, fb.green_mask) << fb.green_pos;
    let blue = scale(b, fb.blue_mask) << fb.blue_pos;
    red | green | blue
}

#[inline(always)]
fn scale(v: u8, mask: u8) -> u32 {
    if mask == 0 {
        0
    } else if mask >= 8 {
        v as u32
    } else {
        (v as u32) >> (8 - mask)
    }
}

